"""Designs the vital-sign IIR filters and writes them as CMSIS-DSP biquad tables.

usage: python gen_filters.py   (rewrites ../src/algo/generated/filters.hpp)

CMSIS arm_biquad_cascade_df2T_f32 wants {b0, b1, b2, -a1, -a2} per stage
(its feedback taps are added, scipy's are subtracted).
"""
from pathlib import Path

import numpy as np
from scipy import signal

ECG_FS = 125.0   # ADS1292R output rate
RESP_FS = 5.0    # Bio-Z after 25:1 block averaging
PPG_FS = 25.0    # MAX30101 output rate (50 sps, 2-sample average)

FILTERS = {
    # Pan-Tompkins QRS band
    "kEcgBandpass": signal.butter(2, [5.0, 15.0], "bandpass", fs=ECG_FS, output="sos"),
    # breathing 6..45 /min: 2nd-order high-pass 0.1 Hz + 4th-order low-pass 0.75 Hz
    "kRespBandpass": np.vstack([
        signal.butter(2, 0.1, "highpass", fs=RESP_FS, output="sos"),
        signal.butter(4, 0.75, "lowpass", fs=RESP_FS, output="sos"),
    ]),
    # pulse 30..240 /min
    "kPpgBandpass": signal.butter(2, [0.5, 4.0], "bandpass", fs=PPG_FS, output="sos"),
}


def cmsis(sos):
    out = []
    for b0, b1, b2, _a0, a1, a2 in sos:
        out += [b0, b1, b2, -a1, -a2]
    return out


def main():
    root = Path(__file__).resolve().parent.parent
    lines = [
        "// Generated by tools/gen_filters.py -- do not edit.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstddef>",
        "",
        "namespace dev::algo::coeffs {",
        "",
        f"inline constexpr float kEcgFs = {ECG_FS:.1f}f;",
        f"inline constexpr float kRespFs = {RESP_FS:.1f}f;",
        f"inline constexpr float kPpgFs = {PPG_FS:.1f}f;",
        "",
    ]
    for name, sos in FILTERS.items():
        c = cmsis(sos)
        lines.append(f"inline constexpr std::size_t {name}Stages = {len(sos)};")
        lines.append(f"inline constexpr std::array<float, {len(c)}> {name} = {{")
        for i in range(0, len(c), 5):
            lines.append("\t" + ", ".join(f"{v:.9e}f" for v in c[i:i + 5]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("} // namespace dev::algo::coeffs")
    out = root / "src" / "algo" / "generated" / "filters.hpp"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    np.savez(root / "tests" / "host" / "filters_ref.npz", **{k: v for k, v in FILTERS.items()})
    print("wrote", out)


if __name__ == "__main__":
    main()
